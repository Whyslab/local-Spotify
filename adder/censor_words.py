"""Слова, которые лейблы приглушают в перевыпусках русского рэпа.

С осени 2025 студийные записи на YouTube Music выходят с приглушёнными словами
про наркотики (закон 23.07.2024, в силе с 01.03.2026); мат обычно оставлен,
но бывает и он. Тихое место в студийной записи само по себе ничего не доказывает
(другое сведение тоже где-то тише) — цензуру подтверждает только строка текста
со словом отсюда на том же месте (разбор 19.11.2026).

Основы, а не точные слова: «курим», «раскурил», «накурен» — одна основа. Ложные
совпадения отсечены границами слова и исключениями («курица», «план на завтра»).
"""

import re

# Наркотики и всё вокруг них, как это поют. Основа + любое окончание.
DRUG_STEMS = (
    r"(?:на|рас|у|по|за|при|об|под|до)?кур(?:им|ит|ят|ю|и|ил|ила|или|ишь|ите|ен|ена|ены|ево|енн\w*|нул\w*|ну\b)",
    r"(?:рас|на)?курива\w*",
    r"сатив\w*",
    r"индик\w*",
    r"дур[ьиюя]\b",
    r"шишк\w*",
    r"шмал\w*",
    r"травк\w*",
    r"ганд?ж\w*",  # ганжа, ганджубас
    r"марихуан\w*",
    r"амфетамин\w*",
    r"закладк\w*",
    r"пыхн\w*",
    r"гаш(?:иш\w*|ик\w*)?\b",  # не «гашу свет», не «гашетка»
    r"косяк\w*",
    r"джоинт\w*",
    r"бошк\w*",
    r"бонг\w*",
    r"зипл?ок\w*",
    r"окси\w*",
    r"кодеин\w*",
    r"лин\b",
    r"лина\b",
    r"сироп\w*",
    r"молли\b",
    r"мдма\w*",
    r"экстази\w*",
    r"кокс\w*",
    r"кокаин\w*",
    r"порош\w*",
    r"дорожк\w*",
    r"нюха\w*",
    r"занюх\w*",
    r"меф\w*",
    r"фен\b",
    r"колес(?:а|ами|ах)\b",  # «колёса» — таблетки; «кручу колесо» — нет
    r"таблет\w*",
    r"ксанакс\w*",
    r"барбитур\w*",
    r"героин\w*",
    r"план\w*\s+(?:в|на)\s+(?:бонг|косяк|руке)",  # «план» — только в таком виде
    r"накур\w*",
    r"упорот\w*",
    r"уколот\w*",
    r"high\b",
    r"weed\b",
    r"lean\b",
    r"xanax\w*",
    r"percs?\b",
    r"percocet\w*",
    r"molly\b",
    r"dope\b",
    r"doup\b",
    r"доуп\w*",
    r"блант\w*",
    r"blunt\w*",
)

# Мат: основы. Лейблы приглушают его реже, но бывает.
SWEAR_STEMS = (
    r"\w*ху[йяеёию]\w*",
    r"\w*пизд\w*",
    r"бля\w*",
    r"(?:за|у|на|вы|до|при|от|по|съ|въ|раз|разъ|об|подъ|е)?[её]б(?:а|у|ы|и|л|н|ш)\w*",
    r"сук[аиуеой]?\b",
    r"сучк\w*",
    r"мудак\w*",
    r"муд[ао]зв\w*",
    r"пидор\w*",
    r"пидар\w*",
    r"залуп\w*",
    r"fuck\w*",
    r"shit\w*",
    r"bitch\w*",
)

# Слова, которые начинаются как основа выше, но к делу не относятся.
_NOT = re.compile(
    r"\b(?:куриц\w*|курин\w*|куран\w*|курорт\w*|курс\w*|куртк\w*|курьер\w*|курок\w*|"
    r"окситоцин\w*|индиго|индикатор\w*|индиан\w*|линия|фенечк\w*|феникс\w*|"
    r"колесниц\w*|highway\w*|"
    r"героин(?:я|и|е|ю|ей|ями?|ях)|оксид\w*|окситан\w*|мефоди\w*|мефисто\w*|"
    r"perch\w*|perce\w*|perf\w*|rawr|страхуй\w*|застрахуй\w*|хуйня-не)\b",
    re.IGNORECASE,
)

_DRUG = re.compile(r"(?<![\w])(?:" + "|".join(DRUG_STEMS) + r")", re.IGNORECASE)
_SWEAR = re.compile(r"(?<![\w])(?:" + "|".join(SWEAR_STEMS) + r")", re.IGNORECASE)


def _fold(line: str) -> str:
    return line.replace("ё", "е").replace("Ё", "Е")


def _find(pattern: re.Pattern, line: str) -> list[str]:
    text = _fold(line)
    blocked = [m.span() for m in _NOT.finditer(text)]
    return [
        m.group(0)
        for m in pattern.finditer(text)
        if not any(a <= m.start() < b for a, b in blocked)
    ]


def drug_hits(line: str) -> list[str]:
    """Слова про наркотики — их перевыпуски и глушат (сильный признак)."""
    return _find(_DRUG, line)


def swear_hits(line: str) -> list[str]:
    """Мат — его обычно оставляют; совпадение с тихим местом — слабый признак
    (у клипа своё сведение тоже где-то тише)."""
    return _find(_SWEAR, line)


def hits(line: str) -> list[str]:
    """Слова строки, которые лейбл мог приглушить: ``["курим", "дурь"]``."""
    return drug_hits(line) + swear_hits(line)
