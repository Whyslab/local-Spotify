"""Словарь «что могли приглушить»: строки из подтверждённых случаев 19.11.2026
находятся, обычные слова — нет."""

import pytest

from adder.censor_words import hits

# Строки, на которые пришлись приглушённые места (разбор и этап 1, 19.11.2026).
CENSORED = [
    "Курю ганджубас на балконе",
    "Марихуана в кармане",
    "Закладки по району",
    "Дай пыхнуть разок",
    "Курим дурь и жарим кур на гриле",  # GLAM!
    "Я раскурил и воспарил, из низов, но исполин",
    "Оу, курю Raw, док",
    "Смоук, курим доуп, бро",
    "80 окси переводит меня в слоу",  # Наличные
    "Пока мы high все эти лохи на лоу",
    "30 20 бинов этот черный белый как таблетки",
    "Сквирт шампанского в зиплоке",  # Champagne Squirt
    "Нет истерики сативной, ей так нравится эффект",
    "Сквирт шампанского в лицо мне, она курит наравне",
    "Да, я ёбаный G.O.A.T",  # мат
    "Но мне похуй вообще",
    "Я помню улицу, блять, на которой рос",
]

CLEAN = [
    "Гашу свет и ухожу",
    "Она героиня этого кино",
    "Нет у этой героини имени",
    "Оксид железа",
    "Слышу percussion в ушах",
    "Ганг течёт в Индии",
    "Закатом любуюсь",
    "Твои волосы на afterparty после вечеринки моего концерта",
    "Курица на ужин и курс на юг",
    "Я купил себе куртку и тебе тоже",
    "Мне не надо тебя, мне не надо себя",
    "Небо над головой",
    "План на завтра простой",
    "Колесница несётся вперёд",
    "Highway to the danger zone",
    "Застрахуй машину",
    "Сукно и бархат",
    "Поле чудес, я кручу колесо",  # ложное в разборе 19.11
]


@pytest.mark.parametrize("line", CENSORED)
def test_lines_that_were_muted_are_found(line):
    assert hits(line), line


@pytest.mark.parametrize("line", CLEAN)
def test_ordinary_words_are_not(line):
    assert hits(line) == [], (line, hits(line))


def test_it_says_which_words():
    assert [w.lower() for w in hits("Курим дурь и жарим кур на гриле")] == ["курим", "дурь"]


def test_drugs_and_swearing_are_told_apart():
    """Мат лейблы обычно оставляют — он слабый признак, наркотики — сильный."""
    from adder.censor_words import drug_hits, swear_hits

    assert drug_hits("Да, я ёбаный G.O.A.T") == []
    assert swear_hits("Да, я ёбаный G.O.A.T")
    assert drug_hits("Индика — подруга") and swear_hits("Индика — подруга") == []
